"""Pull request text for a verified fix: title, body and commit message.

Written for a maintainer who has never heard of apifix, from verification.json and
trajectory.json (report.md is written for apifix's own users). Pure functions, no I/O.
"""

from __future__ import annotations

import re
from collections import Counter
from collections.abc import Sequence
from dataclasses import dataclass
from typing import Any
from urllib.parse import urlparse

from apifix.engine.build_info import build_label
from apifix.engine.migrations import Migration

LIST_LIMIT = 10
MAIN_CHANGES = 5
UNCOVERED_LIMIT = 40
CODE_WIDTH = 80
DISCLOSURE_CLOSING = "Feel free to close this if it isn't useful."


@dataclass(frozen=True)
class ChangedFile:
    path: str
    added: int
    deleted: int


@dataclass(frozen=True)
class _Edit:
    """One run of changed lines in a diff: the old lines it removed and the text it added."""

    first: int  # first old line removed
    last: int  # last old line removed
    added: str


@dataclass(frozen=True)
class PullRequestText:
    title: str
    body: str
    commit_message: str


def _code(text: str) -> str:
    """Inline code: one line, clipped, with no backticks to break the span."""
    text = " ".join(text.replace("`", "'").split())
    if len(text) > CODE_WIDTH:
        text = text[: CODE_WIDTH - 1] + "…"
    return f"`{text}`"


def _count(n: int, noun: str) -> str:
    """`1 file`, `3 files`."""
    return f"{n} {noun}" + ("" if n == 1 else "s")


def _bullets(items: Sequence[str]) -> list[str]:
    """Bullet lines, the first LIST_LIMIT visible and the rest in a collapsed block."""
    lines = [f"- {item}" for item in items[:LIST_LIMIT]]
    rest = items[LIST_LIMIT:]
    if rest:
        lines += [
            f"- and {len(rest)} more:",
            "",
            "<details><summary>the rest</summary>",
            "",
            *[f"  - {item}" for item in rest],
            "",
            "</details>",
        ]
    return lines


def _span(entry: dict[str, Any]) -> str:
    start, end = entry["line"], entry.get("end_line") or entry["line"]
    return f"{entry['file']}:{start}" + (f"-{end}" if end != start else "")


def _hunk_line(entry: dict[str, Any]) -> str:
    what = entry.get("new") or entry.get("old") or ""
    return f"`{_span(entry)}`" + (f": {_code(what)}" if what else "")


def _counts_row(label: str, run: dict[str, Any]) -> str:
    c = run.get("counts") or {}
    if run.get("status") in ("error", "timeout") and not c.get("total"):
        return f"| {label} | did not run ({run.get('status')}) | | | |"
    return (
        f"| {label} | {c.get('passed', 0)} | {c.get('failed', 0)} | "
        f"{c.get('errors', 0)} | {c.get('skipped', 0)} |"
    )


def _build_text(build: dict[str, Any]) -> str:
    """`0.1.0 (git commit abc123...)`; build_label() would describe this process instead of the
    one that made the run when the run recorded none."""
    return build_label(build) if build else "(build not recorded)"


def _model_name(job: dict[str, Any]) -> str | None:
    """The model without a vendor prefix (`openai/gpt-oss-120b` -> `gpt-oss-120b`), so it does not
    read as if that vendor wrote the change."""
    return (job.get("model") or "").rsplit("/", 1)[-1] or None


def _host(job: dict[str, Any]) -> str | None:
    """The LLM endpoint's host (`api.example.com`), None when the run recorded no endpoint."""
    return urlparse(job.get("endpoint") or "").hostname


def _tested_version(v: dict[str, Any], migration: Migration) -> str | None:
    """`openai 2.54.0`: the library version the fixed run's tests ran with."""
    version = ((v["runs"]["fixed"].get("smoke") or {}).get("version")) or None
    return f"{migration.package} {version}" if version else None


def _opening(v: dict[str, Any], job: dict[str, Any], migration: Migration) -> list[str]:
    model = _model_name(job)
    using = f" (using {model})" if model else ""
    tested = _tested_version(v, migration)
    return [
        f"This PR was generated by apifix, an automated migration tool{using}, and verified by "
        "running the repo's tests before and after the change. Please review it like any other "
        "contribution.",
        "",
        f"It moves the code from {migration.source_name} to the current API"
        + (f" (tests ran with {tested})" if tested else "")
        + ".",
        "",
    ]


def _weak_section(v: dict[str, Any]) -> list[str]:
    weak = [r["message"].splitlines()[0] for r in v["reasons"] if r["severity"] == "weak"]
    cov = v["changed_line_coverage"]
    if cov["available"] and cov["executable"] and not any("coverage" in m.lower() for m in weak):
        weak.append(f"only {cov['executed']}/{cov['executable']} changed lines ran in the tests")
    lines = [
        "> **What the tests did not cover.** This change is only weakly verified: part of it "
        "is code that no test runs, so it needs a careful read.",
        *[f"> - {m}" for m in weak[:LIST_LIMIT]],
    ]
    if v["review_by_hand"]:
        lines.append("> - Not run by any test:")
        shown = v["review_by_hand"][:LIST_LIMIT]
        lines += [f">   - {_hunk_line(h)}" for h in shown]
        if len(v["review_by_hand"]) > len(shown):
            lines.append(f">   - and {len(v['review_by_hand']) - len(shown)} more")
    return lines + [""]


def _edit(removed: list[int], added: list[str]) -> _Edit:
    return _Edit(removed[0], removed[-1], "\n".join(added))


_HUNK_HEADER = re.compile(r"^@@ -(\d+)(?:,(\d+))? \+\d+(?:,(\d+))? @@")


def _diff_edits(diff: str) -> dict[str, list[_Edit]]:
    """Per file, the runs of removed and added lines of a unified diff (context lines split
    them), with the old line numbers the removed lines had."""
    edits: dict[str, list[_Edit]] = {}
    path: str | None = None
    lines = diff.splitlines()
    i = 0
    while i < len(lines):
        line = lines[i]
        i += 1
        if line.startswith("+++ "):
            name = line[4:].split("\t")[0]
            path = name[2:] if name.startswith("b/") else None
            continue
        header = _HUNK_HEADER.match(line)
        if not header or path is None:
            continue
        old_left = int(header[2] if header[2] is not None else 1)
        new_left = int(header[3] if header[3] is not None else 1)
        old_line = int(header[1])
        removed: list[int] = []
        added: list[str] = []
        while (old_left > 0 or new_left > 0) and i < len(lines):
            line = lines[i]
            i += 1
            if line.startswith("\\"):
                continue
            if line.startswith("-"):
                removed.append(old_line)
                old_line += 1
                old_left -= 1
            elif line.startswith("+"):
                added.append(line[1:])
                new_left -= 1
            else:  # context ends a run of changes
                if removed:
                    edits.setdefault(path, []).append(_edit(removed, added))
                removed, added = [], []
                old_line += 1
                old_left -= 1
                new_left -= 1
        if removed:
            edits.setdefault(path, []).append(_edit(removed, added))
    return edits


def _fixed_code(edits: dict[str, list[_Edit]], finding: dict[str, Any]) -> tuple[str, str] | None:
    """(the code the diff put where a finding's old code was, every line the diff added to its
    file), None when the diff did not touch the finding's lines."""
    first = finding["line"]
    last = finding.get("end_line") or first
    here = [e.added for e in edits.get(finding["file"], []) if e.first <= last and e.last >= first]
    if not here:
        return None
    return "\n".join(here), "\n".join(e.added for e in edits[finding["file"]])


def _main_changes(
    v: dict[str, Any], trajectory: dict[str, Any], migration: Migration, diff: str
) -> list[str]:
    """Up to MAIN_CHANGES "old -> new" bullets for the findings the change resolved, the most
    common first, each built from the finding's old code and what the diff put there. A remaining
    finding is matched without its line, which the fix moved."""
    edits = _diff_edits(diff)
    remaining = Counter(
        (r["file"], r["category"], r["old_pattern"]) for r in v["remaining_findings"]
    )
    bullets: Counter[str] = Counter()
    for f in trajectory.get("findings") or []:
        key = (f["file"], f["category"], f["old_pattern"])
        if remaining[key]:
            remaining[key] -= 1
            continue
        fixed = _fixed_code(edits, f)
        bullet = fixed and migration.pr_change(f["category"], f["old_pattern"], *fixed)
        if bullet:
            bullets[bullet] += 1
    if not bullets:
        return []
    return ["## Main changes", "", *[f"- {b}" for b, _ in bullets.most_common(MAIN_CHANGES)], ""]


def _pin_why(pins: Sequence[dict[str, Any]], migration: Migration) -> str:
    """The reason for each clause of the migration's pin that apifix wrote, from its data."""
    written = " ".join(p["new"] for p in pins if p.get("kind") == "migration")
    return ", ".join(
        f"`{clause}` ({reason})"
        for clause, reason in migration.pin_reasons.items()
        if re.search(re.escape(clause) + r"(?![\w.])", written)
    )


def _what_changed(
    v: dict[str, Any], job: dict[str, Any], files: Sequence[ChangedFile], migration: Migration
) -> list[str]:
    added = sum(f.added for f in files)
    deleted = sum(f.deleted for f in files)
    lines = [f"- {_count(len(files), 'file')} changed (+{added} −{deleted}):"]
    lines += [f"  - `{f.path}`" for f in files[:LIST_LIMIT]]
    if len(files) > LIST_LIMIT:
        lines.append(f"  - and {len(files) - LIST_LIMIT} more")
    before, left = v["findings_before"], len(v["remaining_findings"])
    lines.append(
        f"- Findings (places where the old API is used) resolved: {before - left} of {before}"
        + (f"; {left} left, listed below" if left else "")
    )
    pins = job.get("pin_edits") or []
    if pins:
        lines.append(f"- Dependency {'pin' if len(pins) == 1 else 'pins'} set:")
        lines += [f"  - `{p['file']}`: {_code(p['old'])} → {_code(p['new'])}" for p in pins[:5]]
        if len(pins) > 5:
            lines.append(f"  - and {len(pins) - 5} more")
        why = _pin_why(pins, migration)
        if why:
            lines.append(f"  - Why this range: {why}")
    return lines


def _spans(lines: Sequence[int]) -> list[tuple[int, int]]:
    """Sorted line numbers -> (first, last) runs."""
    runs: list[list[int]] = []
    for n in sorted(lines):
        if runs and n == runs[-1][1] + 1:
            runs[-1][1] = n
        else:
            runs.append([n, n])
    return [(a, b) for a, b in runs]


def _uncovered_section(cov: dict[str, Any]) -> list[str]:
    """The changed lines no test ran, collapsed. Runs made before apifix recorded them have
    none (only the counts)."""
    spans = [
        f"{path}:{a}" + (f"-{b}" if b != a else "")
        for path, nums in sorted((cov.get("uncovered") or {}).items())
        for a, b in _spans(nums)
    ]
    if not spans:
        return []
    total = sum(len(n) for n in cov["uncovered"].values())
    shown = [f"`{span}`" for span in spans[:UNCOVERED_LIMIT]]
    if len(spans) > UNCOVERED_LIMIT:
        shown.append(f"and {len(spans) - UNCOVERED_LIMIT} more")
    return [
        "",
        f"<details><summary>{_count(total, 'changed line')} no test ran</summary>",
        "",
        ", ".join(shown),
        "",
        "</details>",
    ]


def _test_edits_section(v: dict[str, Any]) -> list[str]:
    edits = v["test_edits"]
    if not edits:
        return []
    problems = [e for e in edits if e["severity"] != "info"]
    if problems:
        items = [f"`{e['file']}:{e['line']}`: {e['kind']}: {_code(e['detail'])}" for e in problems]
        return ["", "Test edits that need a look:", "", *_bullets(items)]
    files = sorted({e["file"] for e in edits})
    names = ", ".join(f"`{f}`" for f in files[:5]) + (
        f" and {len(files) - 5} more" if len(files) > 5 else ""
    )
    return [
        "",
        f"Test {'file' if len(files) == 1 else 'files'} edited ({names}): the tests' mocks and "
        "imports were updated to the new API; apifix checked that no test or assertion was "
        "removed, skipped or weakened.",
    ]


def _tests_section(v: dict[str, Any]) -> list[str]:
    runs, delta, cov = v["runs"], v["tests"], v["changed_line_coverage"]
    lines = [
        "| | passed | failed | errors | skipped |",
        "|---|---|---|---|---|",
        _counts_row("Before (unmodified code)", runs["baseline"]),
        _counts_row("After (with this change)", runs["fixed"]),
        "",
    ]
    facts = []
    fixed_by = len(delta["fixed_by_change"])
    if fixed_by:
        facts.append(
            f"{_count(fixed_by, 'test')} failing before now {'passes' if fixed_by == 1 else 'pass'}"
        )
    if delta["new_tests"]:
        facts.append(_count(len(delta["new_tests"]), "new test"))
    if cov["available"] and cov["executable"]:
        facts.append(f"changed lines executed by the tests: {cov['executed']}/{cov['executable']}")
    else:
        facts.append("changed-line coverage was not available")
    text = "; ".join(facts)
    lines.append(text[:1].upper() + text[1:] + ".")
    if cov["available"] and cov["executed"] < cov["executable"]:
        lines += _uncovered_section(cov)
    return lines + _test_edits_section(v)


def _review_section(v: dict[str, Any]) -> list[str]:
    items = []
    if v["verdict"] != "verified_weak":  # the weak notice already lists these hunks
        items += [f"{_hunk_line(h)} (no test runs this)" for h in v["review_by_hand"]]
    items += [
        f"`{e['file']}:{e['line']}`: {e['category']}, still uses {_code(e['old_pattern'])}"
        + ("" if e["changed"] else " (line not changed)")
        for e in v["review_findings"]
    ]
    return ["## Please review by hand", "", *_bullets(items), ""] if items else []


def _lockfile_section(lockfiles: Sequence[str]) -> list[str]:
    if not lockfiles:
        return []
    names = ", ".join(f"`{name}`" for name in lockfiles)
    return [
        "## Lockfiles",
        "",
        f"Not regenerated: {names}. The repo's CI may fail until "
        f"{'it is' if len(lockfiles) == 1 else 'they are'} regenerated.",
        "",
    ]


def _checked_section(v: dict[str, Any], job: dict[str, Any], build: dict[str, Any]) -> list[str]:
    fixed = v["runs"]["fixed"]
    python = fixed.get("python") or "?"
    placeholders = job.get("sandbox_env_placeholders") or fixed.get("env_placeholders") or []
    env = (
        f"; placeholder values (not real keys) were set for {', '.join(placeholders)}"
        if placeholders
        else ""
    )
    lines = [
        "## How it was checked",
        "",
        f"The repo's tests ran in Docker (Python {python}), first on the unmodified code and "
        "then with this change. Dependencies were installed from a generated requirements file "
        "(the only step with network access; it saw no repo code). The tests themselves ran "
        f"with no network and no secrets{env}.",
        "",
        f"Checked by apifix {_build_text(build)}.",
    ]
    if build.get("dirty"):
        lines.append(
            "That apifix build had uncommitted changes, so the commit does not exactly "
            "describe the code that ran."
        )
    return lines + [""]


def _recheck_section(migration: Migration, base: str, repo_url: str | None) -> list[str]:
    if not repo_url:
        return []
    return [
        "## Re-check it",
        "",
        f"With [apifix]({repo_url}) installed, from a checkout of this branch:",
        "",
        "```",
        f"git diff {base[:12]}..HEAD > fix.diff",
        f"apifix verify . --migration {migration.name} --diff fix.diff",
        "```",
        "",
    ]


def _written_by(job: dict[str, Any]) -> str:
    model = _model_name(job)
    if not model:
        return "Written by: not recorded (the diff came from `apifix verify`)"
    return f"Written by: {model}"


def title_for(migration: Migration) -> str:
    return f"Migrate to the {migration.target_name} API"


def build_pull_request_text(
    verification: dict[str, Any],
    trajectory: dict[str, Any],
    migration: Migration,
    *,
    files: Sequence[ChangedFile],
    base: str,
    diff: str = "",
    lockfiles: Sequence[str] = (),
    repo_url: str | None = None,
) -> PullRequestText:
    """Title, body and commit message. `diff`: the change (the main changes come from it);
    `lockfiles`: lockfiles the change leaves stale; `repo_url`: apifix's home page (the
    re-check section is left out without one)."""
    job = trajectory["job"]
    build = job.get("apifix") or {}
    v = verification
    weak = v["verdict"] == "verified_weak"
    body = _opening(v, job, migration)
    if weak:
        body += _weak_section(v)
    body += ["## Why", "", migration.pr_why, ""]
    body += _main_changes(v, trajectory, migration, diff)
    body += ["## What changed", ""]
    body += _what_changed(v, job, files, migration) + ["", "## Tests", ""]
    body += _tests_section(v) + [""]
    body += _review_section(v)
    body += _lockfile_section(lockfiles)
    body += _checked_section(v, job, build)
    body += _recheck_section(migration, base, repo_url)
    body += [DISCLOSURE_CLOSING]
    commit = [
        title_for(migration),
        "",
        f"Moves the code from {migration.source_name} to {migration.target_name}.",
        "",
        _written_by(job),
        f"Verified by: apifix {_build_text(build)}",
        f"Verdict: {v['verdict']}",
    ]
    return PullRequestText(
        title=title_for(migration),
        body="\n".join(body).rstrip() + "\n",
        commit_message="\n".join(commit) + "\n",
    )
